#!/usr/bin/env bash
# Real-format integration tests for Quick Archive's libarchive reader.
set -Eeuo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/omnish-archive-real.XXXXXX")"
trap 'rm -rf -- "$WORK"' EXIT

for tool in bsdtar genisoimage gcab ar; do
    command -v "$tool" >/dev/null 2>&1 || {
        printf 'Missing real-archive test dependency: %s\n' "$tool" >&2
        exit 2
    }
done

source "$ROOT/lib/55-archive.sh"

FIXTURES="$WORK/fixture source"
mkdir -p -- "$FIXTURES"
printf 'real libarchive payload\n' > "$FIXTURES/payload.txt"
printf 'nested payload\n' > "$FIXTURES/nested file.txt"

assert_archive_member() {
    local archive="$1" member="$2" expected="$3" kind index actual before after
    kind="$(_archive_kind "$archive")"
    [[ "$kind" == libarchive ]] || {
        printf 'Expected libarchive reader for %s, got %s\n' "${archive##*/}" "$kind" >&2
        return 1
    }
    index="$(_archive_list_to "$archive")"
    grep -Fxq -- "$member" <<< "$index" || {
        printf 'Member %s missing from %s listing:\n%s\n' "$member" "${archive##*/}" "$index" >&2
        return 1
    }
    before="$(sha256sum "$archive" | awk '{print $1}')"
    actual="$(_archive_stream_member "$archive" "$member")"
    after="$(sha256sum "$archive" | awk '{print $1}')"
    [[ "$actual" == "$expected" ]] || {
        printf 'Unexpected streamed content from %s:%s\n' "${archive##*/}" "$member" >&2
        return 1
    }
    [[ "$before" == "$after" ]] || {
        printf 'Read-only browse modified %s\n' "${archive##*/}" >&2
        return 1
    }
}

# 7z: produced by libarchive's writer, then independently reopened by its reader.
SEVEN_Z="$WORK/fixture.7z"
bsdtar --format=7zip -cf "$SEVEN_Z" -C "$FIXTURES" payload.txt
assert_archive_member "$SEVEN_Z" payload.txt "real libarchive payload"

# ISO-9660: generated with Rock Ridge/Joliet metadata.
ISO="$WORK/fixture.iso"
genisoimage -quiet -R -J -o "$ISO" "$FIXTURES"
assert_archive_member "$ISO" payload.txt "real libarchive payload"

# Microsoft Cabinet: generated with gcab and read through bsdtar.
CAB="$WORK/fixture.cab"
(
    cd -- "$FIXTURES"
    gcab -c "$CAB" payload.txt
)
assert_archive_member "$CAB" payload.txt "real libarchive payload"

# Unix ar archive: generated by binutils and read through bsdtar.
AR="$WORK/fixture.ar"
(
    cd -- "$FIXTURES"
    ar rcs "$AR" payload.txt
)
assert_archive_member "$AR" payload.txt "real libarchive payload"

# RAR is deliberately fail-closed for invalid data. RAR encoders are not
# generally available in the Ubuntu runner's free toolchain, so this test
# does not pretend that a renamed file is a genuine RAR fixture.
printf 'not a RAR archive\n' > "$WORK/not-a-rar.rar"
[[ "$(_archive_kind "$WORK/not-a-rar.rar")" == unknown ]] || {
    echo "Malformed RAR data was incorrectly accepted" >&2
    exit 1
}
archive_is_supported "$WORK/not-a-rar.rar" || {
    echo "RAR extension is not advertised for archive browsing" >&2
    exit 1
}

printf 'PASS: real 7z, ISO-9660, CAB and ar archives listed/streamed read-only; malformed RAR rejected.\n'
